"""Minimal, safe GitHub REST client for reviewable improvement pull requests.

Requires a fine-grained token with Contents: read/write and Pull requests: read/write.
Repository metadata is read-only. No merge, delete, or force-update operation exists.
"""

from __future__ import annotations

import json
import os
import re
import secrets
import time
from dataclasses import dataclass
from typing import Any
from urllib.error import HTTPError, URLError
from urllib.request import Request, urlopen

# ruff: noqa: E501
# fmt: off


API_ROOT = "https://api.github.com"
API_VERSION = "2022-11-28"
_TIMEOUT_SECONDS = 20


class GitHubError(RuntimeError):
    """Base error for GitHub integration."""


class GitHubAuthenticationError(GitHubError):
    """The token is missing, invalid, or expired."""


class GitHubPermissionError(GitHubError):
    """The token lacks a required repository permission."""


class GitHubRateLimitError(GitHubError):
    """GitHub rejected a request because of a rate limit."""


class GitHubAPIError(GitHubError):
    """GitHub returned an unexpected API error."""


@dataclass(frozen=True)
class PullRequestResult:
    number: int
    url: str
    branch: str
    base: str
    commit_sha: str


def _validate_repo_name(repository: str) -> str:
    if not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", repository):
        raise ValueError("Repository must use the owner/name format.")
    return repository


def _validate_path(path: str) -> str:
    if (
        not path
        or path.startswith("/")
        or "\\" in path
        or any(part in {"", ".", ".."} for part in path.split("/"))
        or path.endswith("/")
    ):
        raise ValueError(f"Unsafe repository path: {path!r}")
    return path


def build_pull_request_body(
    files: list[dict[str, str]], base_branch: str, audit_summary: str = ""
) -> str:
    """Build a transparent PR body with exact proposed paths and safety notes."""
    lines = [
        "## Repo Fixer — proposed repository improvements",
        "",
        "This pull request was generated by Repo Fixer for human review.",
        "",
        "### Proposed files",
    ]
    lines.extend(f"- `{item['path']}` — {item.get('reason', 'Missing repository essential')}" for item in files)
    if audit_summary:
        lines.extend(["", "### Audit context", "", audit_summary.strip()])
    lines.extend(
        [
            "",
            "### Safety and review",
            "",
            "- Changes are additions only; no existing file was replaced or deleted.",
            "- The changes were committed to a separate feature branch.",
            "- No direct push to the default branch, force-push, or automatic merge was performed.",
            "- Review every generated file and run the repository's checks before merging.",
            "",
            f"**Target branch:** `{base_branch}`",
            "",
            "Generated by Repo Fixer. This pull request is not approved for automatic merging.",
        ]
    )
    return "\n".join(lines)


class GitHubClient:
    """Small urllib-based GitHub API client with explicit error classification."""

    def __init__(self, token: str, *, timeout: int = _TIMEOUT_SECONDS) -> None:
        if not token or not token.strip():
            raise GitHubAuthenticationError(
                "Set GITHUB_TOKEN to a fine-grained GitHub token."
            )
        self._token = token.strip()
        self._timeout = timeout

    @classmethod
    def from_environment(cls) -> GitHubClient:
        return cls(os.environ.get("GITHUB_TOKEN", ""))

    def _request(
        self, method: str, endpoint: str, payload: dict[str, Any] | None = None
    ) -> tuple[dict[str, Any], dict[str, str]]:
        url = endpoint if endpoint.startswith("https://") else f"{API_ROOT}{endpoint}"
        data = None if payload is None else json.dumps(payload).encode("utf-8")
        request = Request(
            url,
            data=data,
            method=method,
            headers={
                "Accept": "application/vnd.github+json",
                "Authorization": f"Bearer {self._token}",
                "X-GitHub-Api-Version": API_VERSION,
                "User-Agent": "Repo-Fixer",
                **({"Content-Type": "application/json"} if data is not None else {}),
            },
        )
        try:
            with urlopen(request, timeout=self._timeout) as response:
                raw = response.read()
                headers = {key.lower(): value for key, value in response.headers.items()}
                return (json.loads(raw.decode("utf-8")) if raw else {}), headers
        except HTTPError as exc:
            raw = exc.read()
            try:
                detail = json.loads(raw.decode("utf-8")).get("message", "GitHub API error")
            except (UnicodeDecodeError, json.JSONDecodeError, AttributeError):
                detail = "GitHub API error"
            headers = {key.lower(): value for key, value in exc.headers.items()}
            if exc.code == 401:
                raise GitHubAuthenticationError(
                    "GitHub rejected GITHUB_TOKEN. Check that it is valid and not expired."
                ) from exc
            if exc.code == 403 and (
                headers.get("x-ratelimit-remaining") == "0" or "rate limit" in detail.lower()
            ) or exc.code == 429:
                reset = headers.get("x-ratelimit-reset")
                retry_after = headers.get("retry-after")
                wait = retry_after or (
                    str(max(0, int(reset) - int(time.time()))) if reset and reset.isdigit() else "unknown"
                )
                raise GitHubRateLimitError(
                    f"GitHub rate limit reached. Retry after {wait} seconds."
                ) from exc
            if exc.code == 403:
                raise GitHubPermissionError(
                    "GitHub denied this operation. Check repository Contents and Pull requests permissions."
                ) from exc
            if exc.code == 404:
                raise GitHubAPIError(
                    "GitHub resource not found. Check repository access and branch names."
                ) from exc
            raise GitHubAPIError(f"GitHub API returned HTTP {exc.code}: {detail}") from exc
        except URLError as exc:
            raise GitHubAPIError(f"Could not reach GitHub: {exc.reason}") from exc
        except (TimeoutError, OSError) as exc:
            raise GitHubAPIError(f"GitHub request failed: {exc}") from exc

    def create_improvement_pr(
        self,
        repository: str,
        files: list[dict[str, str]],
        *,
        title: str = "chore: propose repository improvements",
        audit_summary: str = "",
    ) -> PullRequestResult:
        """Create one additions-only commit on a new branch and open a PR."""
        repository = _validate_repo_name(repository)
        if not files:
            raise ValueError("There are no proposed files to include in a pull request.")

        seen: set[str] = set()
        normalized: list[dict[str, str]] = []
        for item in files:
            path = _validate_path(item["path"])
            if path in seen:
                raise ValueError(f"Duplicate proposed path: {path}")
            seen.add(path)
            content = item["content"]
            if not isinstance(content, str):
                raise ValueError(f"File content must be text: {path}")
            normalized.append(
                {"path": path, "content": content, "reason": item.get("reason", "")}
            )

        repo_data, _ = self._request("GET", f"/repos/{repository}")
        if not repo_data.get("permissions", {}).get("push", False):
            raise GitHubPermissionError(
                "Token/user lacks repository Contents write permission (push access)."
            )
        base = repo_data.get("default_branch")
        if not isinstance(base, str) or not base:
            raise GitHubAPIError("GitHub did not return a default branch for this repository.")

        ref_data, _ = self._request(
            "GET", f"/repos/{repository}/git/ref/heads/{base}"
        )
        base_sha = ref_data.get("object", {}).get("sha")
        if not isinstance(base_sha, str):
            raise GitHubAPIError("Could not resolve the default branch commit.")
        commit_data, _ = self._request(
            "GET", f"/repos/{repository}/git/commits/{base_sha}"
        )
        base_tree = commit_data.get("tree", {}).get("sha")
        if not isinstance(base_tree, str):
            raise GitHubAPIError("Could not resolve the default branch tree.")

        tree_data, _ = self._request(
            "GET", f"/repos/{repository}/git/trees/{base_tree}?recursive=1"
        )
        if tree_data.get("truncated"):
            raise GitHubAPIError(
                "Repository tree is too large to verify safely; no branch was created."
            )
        existing = {entry.get("path") for entry in tree_data.get("tree", [])}
        conflicts = sorted(seen.intersection(existing))
        if conflicts:
            raise GitHubAPIError(
                "Refusing to overwrite existing repository paths: " + ", ".join(conflicts)
            )

        branch = f"repo-fixer/improvements-{secrets.token_hex(4)}"
        self._request(
            "POST",
            f"/repos/{repository}/git/refs",
            {"ref": f"refs/heads/{branch}", "sha": base_sha},
        )

        tree_entries: list[dict[str, str]] = []
        for item in normalized:
            blob, _ = self._request(
                "POST",
                f"/repos/{repository}/git/blobs",
                {"content": item["content"], "encoding": "utf-8"},
            )
            tree_entries.append(
                {
                    "path": item["path"],
                    "mode": "100644",
                    "type": "blob",
                    "sha": blob["sha"],
                }
            )

        new_tree, _ = self._request(
            "POST",
            f"/repos/{repository}/git/trees",
            {"base_tree": base_tree, "tree": tree_entries},
        )
        commit, _ = self._request(
            "POST",
            f"/repos/{repository}/git/commits",
            {
                "message": "chore: add proposed repository improvements",
                "tree": new_tree["sha"],
                "parents": [base_sha],
            },
        )
        # A normal fast-forward update only; force is deliberately never sent.
        self._request(
            "PATCH",
            f"/repos/{repository}/git/refs/heads/{branch}",
            {"sha": commit["sha"], "force": False},
        )

        body = build_pull_request_body(normalized, base, audit_summary)
        pull, _ = self._request(
            "POST",
            f"/repos/{repository}/pulls",
            {
                "title": title,
                "head": branch,
                "base": base,
                "body": body,
                "maintainer_can_modify": False,
            },
        )
        return PullRequestResult(
            number=int(pull["number"]),
            url=str(pull["html_url"]),
            branch=branch,
            base=base,
            commit_sha=str(commit["sha"]),
        )
