"""Safety and behavior tests for local file generation."""

from pathlib import Path

import pytest

from repo_fixer.generator import apply_plan, build_plan, detect_language


def test_empty_project_plan_is_non_mutating(tmp_path: Path) -> None:
    plan = build_plan(tmp_path)
    assert plan.created
    assert not list(tmp_path.iterdir())


def test_dry_run_plan_has_all_expected_essentials(tmp_path: Path) -> None:
    plan = build_plan(tmp_path)
    paths = {item.path for item in plan.created}
    assert "README.md" in paths
    assert "CONTRIBUTING.md" in paths
    assert ".github/ISSUE_TEMPLATE/bug_report.yml" in paths
    assert ".github/ISSUE_TEMPLATE/feature_request.yml" in paths
    assert ".github/workflows/ci.yml" in paths


def test_apply_plan_creates_missing_files(tmp_path: Path) -> None:
    plan = build_plan(tmp_path)
    created, skipped = apply_plan(plan)
    assert "README.md" in created
    assert (tmp_path / "README.md").is_file()
    assert not skipped


def test_existing_files_are_skipped(tmp_path: Path) -> None:
    (tmp_path / "CONTRIBUTING.md").write_text("custom", encoding="utf-8")
    plan = build_plan(tmp_path)
    assert not any(item.path == "CONTRIBUTING.md" for item in plan.created)
    assert any("CONTRIBUTING.md" in item for item in plan.skipped)


def test_weak_readme_is_proposed_not_overwritten(tmp_path: Path) -> None:
    readme = tmp_path / "README.md"
    readme.write_text("# My notes", encoding="utf-8")
    plan = build_plan(tmp_path)
    assert readme.read_text(encoding="utf-8") == "# My notes"
    assert any(item.path == "repo-fixer-proposed-README.md" for item in plan.proposed)


def test_force_marks_weak_readme_for_confirmed_replacement(tmp_path: Path) -> None:
    (tmp_path / "README.md").write_text("# Weak", encoding="utf-8")
    plan = build_plan(tmp_path, force=True)
    assert any(item.path == "README.md" and item.replace for item in plan.proposed)


def test_force_replacement_creates_backup(tmp_path: Path) -> None:
    (tmp_path / "README.md").write_text("# Weak", encoding="utf-8")
    plan = build_plan(tmp_path, force=True)
    created, _ = apply_plan(plan, force=True)
    assert (
        (tmp_path / "README.md")
        .read_text(encoding="utf-8")
        .startswith("<!-- Generated")
    )
    backups = list(tmp_path.glob("README.md.repo-fixer-backup-*"))
    assert backups and backups[0].read_text(encoding="utf-8") == "# Weak"


def test_license_requires_explicit_selection(tmp_path: Path) -> None:
    plan = build_plan(tmp_path)
    assert not any(item.path == "LICENSE" for item in plan.created)
    assert any(item.startswith("LICENSE") for item in plan.skipped)


def test_mit_license_is_generated_only_when_selected(tmp_path: Path) -> None:
    plan = build_plan(tmp_path, license_name="MIT")
    license_file = next(item for item in plan.created if item.path == "LICENSE")
    assert "MIT License" in license_file.content


def test_unknown_license_fails_closed(tmp_path: Path) -> None:
    with pytest.raises(ValueError):
        build_plan(tmp_path, license_name="UNLICENSED")


@pytest.mark.parametrize(
    ("marker", "language"),
    [
        ("pyproject.toml", "python"),
        ("package.json", "node"),
        ("go.mod", "go"),
        ("Cargo.toml", "rust"),
    ],
)
def test_language_detection(tmp_path: Path, marker: str, language: str) -> None:
    (tmp_path / marker).write_text("", encoding="utf-8")
    assert detect_language(tmp_path) == language


def test_unknown_language_uses_neutral_workflow(tmp_path: Path) -> None:
    plan = build_plan(tmp_path)
    workflow = next(item for item in plan.created if item.path.endswith("ci.yml"))
    assert "Language-neutral placeholder" in workflow.content


def test_symlink_target_is_rejected(tmp_path: Path) -> None:
    outside = tmp_path.parent / "outside-repo-fixer"
    outside.mkdir(exist_ok=True)
    (tmp_path / ".github").symlink_to(outside, target_is_directory=True)
    with pytest.raises(ValueError, match="symlink"):
        build_plan(tmp_path)


def test_generated_markdown_has_attribution(tmp_path: Path) -> None:
    plan = build_plan(tmp_path)
    readme = next(item for item in plan.created if item.path == "README.md")
    assert "Generated by Repo Fixer" in readme.content


def test_plan_does_not_modify_existing_files(tmp_path: Path) -> None:
    target = tmp_path / "README.md"
    target.write_text("# Preserve me", encoding="utf-8")
    before = target.read_bytes()
    build_plan(tmp_path)
    assert target.read_bytes() == before


def test_write_never_overwrites_racing_existing_file(tmp_path: Path) -> None:
    plan = build_plan(tmp_path)
    item = next(item for item in plan.created if item.path == "README.md")
    (tmp_path / "README.md").write_text("raced", encoding="utf-8")
    from repo_fixer.generator import FixPlan

    only = FixPlan(tmp_path, (item,), (), (), ())
    _, skipped = apply_plan(only)
    assert (tmp_path / "README.md").read_text(encoding="utf-8") == "raced"
    assert any("already exists" in message for message in skipped)


@pytest.mark.parametrize(
    "license_name", ["MIT", "Apache-2.0", "BSD-3-Clause", "GPL-3.0-only"]
)
def test_all_supported_license_texts_are_complete(
    tmp_path: Path, license_name: str
) -> None:
    plan = build_plan(tmp_path, license_name=license_name)
    license_item = next(item for item in plan.created if item.path == "LICENSE")
    assert len(license_item.content) > 1000
    assert (
        "Copyright" in license_item.content
        or "copyright" in license_item.content.lower()
    )
