"""Safe, local-only generation of repository starter files."""

# No network, GitHub API, or subprocess integration is used by this module.
from __future__ import annotations

import os
import re
import shutil
import stat
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from jinja2 import StrictUndefined
from jinja2.sandbox import SandboxedEnvironment

from repo_fixer.scanner import AuditReport, audit_repository

ATTRIBUTION = "<!-- Generated by Repo Fixer. Review and customize before using. -->"
LICENSES = ("MIT", "Apache-2.0", "BSD-3-Clause", "GPL-3.0-only")
TEMPLATES = {
    "README.md": "README.md.j2",
    "CONTRIBUTING.md": "CONTRIBUTING.md.j2",
    "CODE_OF_CONDUCT.md": "CODE_OF_CONDUCT.md.j2",
    ".github/ISSUE_TEMPLATE/bug_report.yml": "bug_report.yml.j2",
    ".github/ISSUE_TEMPLATE/feature_request.yml": "feature_request.yml.j2",
    ".github/PULL_REQUEST_TEMPLATE.md": "PULL_REQUEST_TEMPLATE.md.j2",
    "CHANGELOG.md": "CHANGELOG.md.j2",
}
GITIGNORES = {
    "python": "gitignore-python.j2",
    "node": "gitignore-node.j2",
    "go": "gitignore-go.j2",
    "rust": "gitignore-rust.j2",
}
WORKFLOWS = {
    "python": "ci-python.yml.j2",
    "node": "ci-node.yml.j2",
    "go": "ci-go.yml.j2",
    "rust": "ci-rust.yml.j2",
}


@dataclass(frozen=True)
class PlannedFile:
    path: str
    content: str
    reason: str
    replace: bool = False


@dataclass(frozen=True)
class FixPlan:
    repository: Path
    created: tuple[PlannedFile, ...]
    proposed: tuple[PlannedFile, ...]
    skipped: tuple[str, ...]
    unchanged: tuple[str, ...]

    @property
    def empty(self) -> bool:
        return not (self.created or self.proposed)


def detect_language(root: Path) -> str:
    """Detect the primary project language from well-known manifest files."""
    markers = (
        ("pyproject.toml", "python"),
        ("requirements.txt", "python"),
        ("setup.py", "python"),
        ("package.json", "node"),
        ("go.mod", "go"),
        ("Cargo.toml", "rust"),
    )
    found = [language for marker, language in markers if _regular_file(root, marker)]
    return found[0] if found else "unknown"


def _regular_file(root: Path, relative: str) -> bool:
    path = root / relative
    try:
        if path.is_symlink() or not path.is_file():
            return False
        path.resolve(strict=True).relative_to(root)
        return True
    except (OSError, RuntimeError, ValueError):
        return False


def _safe_target(root: Path, relative: str) -> Path:
    """Validate every existing path component and keep writes inside root."""
    if Path(relative).is_absolute() or ".." in Path(relative).parts:
        raise ValueError(f"Unsafe generated path: {relative}")
    target = root / relative
    current = root
    for part in Path(relative).parts:
        current = current / part
        if current.is_symlink():
            raise ValueError(f"Refusing to follow symlink: {current}")
    try:
        target.parent.resolve(strict=False).relative_to(root)
    except (OSError, RuntimeError, ValueError) as exc:
        raise ValueError(f"Generated path escapes repository: {relative}") from exc
    return target


def _context(root: Path, language: str, license_name: str | None) -> dict[str, Any]:
    name = re.sub(r"[^A-Za-z0-9._ -]", "", root.name).strip() or "Project"
    return {
        "project_name": name,
        "language": language,
        "license": license_name or "Choose a license",
        "attribution": ATTRIBUTION,
    }


def _render(template_name: str, context: dict[str, Any]) -> str:
    """Render packaged templates in a sandbox with strict undefined values."""
    from importlib.resources import files

    template_path = files("repo_fixer").joinpath("templates", template_name)
    source = template_path.read_text(encoding="utf-8")
    env = SandboxedEnvironment(undefined=StrictUndefined, autoescape=False)
    env.globals.clear()
    return env.from_string(source).render(context).rstrip() + "\n"


def _license_text(name: str, year: int, holder: str) -> str:
    """Load a complete canonical SPDX license text from packaged resources."""
    from importlib.resources import files

    if name not in LICENSES:
        raise ValueError(f"Choose one of: {', '.join(LICENSES)}")
    text = files("repo_fixer").joinpath("licenses", name).read_text(encoding="utf-8")
    return (
        text.replace("<year>", str(year))
        .replace("<owner>", holder)
        .replace("<copyright holders>", holder)
        .replace("[yyyy]", str(year))
        .replace("[name of copyright owner]", holder)
    )


def build_plan(
    repository: Path | str = ".",
    *,
    license_name: str | None = None,
    force: bool = False,
) -> FixPlan:
    """Build a non-mutating plan from the existing scanner's findings."""
    supplied = Path(repository).expanduser()
    root = supplied.resolve(strict=True)
    if not root.is_dir():
        raise ValueError(f"Repository path is not a directory: {root}")
    report: AuditReport = audit_repository(root)
    language = detect_language(root)
    context = _context(root, language, license_name)
    created: list[PlannedFile] = []
    proposed: list[PlannedFile] = []
    skipped: list[str] = []
    unchanged: list[str] = []
    missing = {finding.check_id for finding in report.findings}

    readme = next(
        (
            p
            for p in ("README.md", "README.rst", "README.txt", "README")
            if _regular_file(root, p)
        ),
        None,
    )
    if "README" in missing and readme:
        content = _render("README.md.j2", context)
        if force:
            proposed.append(PlannedFile(readme, content, "Replace weak README", True))
        else:
            proposed.append(
                PlannedFile(
                    "repo-fixer-proposed-README.md",
                    content,
                    "Reviewable alternative; existing README preserved",
                )
            )
    elif "README" in missing:
        created.append(
            PlannedFile("README.md", _render("README.md.j2", context), "README missing")
        )

    check_to_path = {
        "CONTRIBUTING": "CONTRIBUTING.md",
        "CODE_OF_CONDUCT": "CODE_OF_CONDUCT.md",
        "PR_TEMPLATE": ".github/PULL_REQUEST_TEMPLATE.md",
        "CHANGELOG": "CHANGELOG.md",
        "ISSUE_TEMPLATES": ".github/ISSUE_TEMPLATE/bug_report.yml",
        "CI": ".github/workflows/ci.yml",
    }
    for check_id, path in check_to_path.items():
        if check_id not in missing:
            unchanged.append(path)
            continue
        if check_id == "CI":
            template = WORKFLOWS.get(language)
            content = (
                _render(template, context)
                if template
                else _render("ci-unknown.yml.j2", context)
            )
            reason = (
                f"{language} workflow"
                if template
                else "Language-neutral placeholder; language could not be detected"
            )
        elif check_id == "ISSUE_TEMPLATES":
            content = _render("bug_report.yml.j2", context)
            reason = (
                "Bug report issue template; feature request template is added alongside"
            )
        else:
            content = _render(TEMPLATES[path], context)
            reason = f"{check_id} missing"
        created.append(PlannedFile(path, content, reason))
        if check_id == "ISSUE_TEMPLATES":
            created.append(
                PlannedFile(
                    ".github/ISSUE_TEMPLATE/feature_request.yml",
                    _render("feature_request.yml.j2", context),
                    "Feature request issue template",
                )
            )

    if "GITIGNORE" in missing:
        template = GITIGNORES.get(language)
        if template:
            created.append(
                PlannedFile(
                    ".gitignore", _render(template, context), f"{language} ignore rules"
                )
            )
        else:
            created.append(
                PlannedFile(
                    ".gitignore",
                    "# Generated by Repo Fixer. Review and customize before using.\n"
                    "# Add language-specific build output, caches, "
                    "and local secrets.\n",
                    "Language-neutral ignore placeholder",
                )
            )

    if "LICENSE" in missing:
        if license_name is None:
            skipped.append(
                "LICENSE — selection required; choose MIT, Apache-2.0, "
                "BSD-3-Clause, or GPL-3.0-only"
            )
        else:
            if license_name not in LICENSES:
                raise ValueError(f"Choose one of: {', '.join(LICENSES)}")
            license_content = _license_text(
                license_name, datetime.now(UTC).year, context["project_name"]
            )
            created.append(
                PlannedFile(
                    "LICENSE",
                    license_content,
                    f"Explicitly selected {license_name} license",
                )
            )
    elif "LICENSE" not in missing:
        unchanged.append("LICENSE — already present")

    # Never replace an existing path during ordinary creation.
    safe_created: list[PlannedFile] = []
    for item in created:
        target = _safe_target(root, item.path)
        if target.exists():
            skipped.append(f"{item.path} — already exists")
        else:
            safe_created.append(item)
    for item in proposed:
        _safe_target(root, item.path)
        if (root / item.path).exists() and not item.replace:
            skipped.append(f"{item.path} — proposed file already exists")
    return FixPlan(
        root, tuple(safe_created), tuple(proposed), tuple(skipped), tuple(unchanged)
    )


def apply_plan(plan: FixPlan, *, force: bool = False) -> tuple[list[str], list[str]]:
    """Write only validated targets; force replacements are backed up first."""
    created: list[str] = []
    skipped = list(plan.skipped)
    for item in plan.created + plan.proposed:
        target = _safe_target(plan.repository, item.path)
        if target.exists():
            if not (force and item.replace):
                skipped.append(f"{item.path} — existing file preserved")
                continue
            if target.is_symlink() or not target.is_file():
                skipped.append(
                    f"{item.path} — not a regular file; refusing replacement"
                )
                continue
            stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%S%fZ")
            backup = target.with_name(f"{target.name}.repo-fixer-backup-{stamp}")
            shutil.copy2(target, backup)
            created.append(str(backup.relative_to(plan.repository)))
        target.parent.mkdir(parents=True, exist_ok=True)
        # Exclusive creation prevents a race from silently overwriting a new file.
        flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL
        if item.replace:
            flags = os.O_WRONLY | os.O_CREAT | os.O_TRUNC
        flags |= getattr(os, "O_NOFOLLOW", 0)
        descriptor = os.open(
            target,
            flags,
            stat.S_IWUSR | stat.S_IRUSR | stat.S_IWGRP | stat.S_IRGRP | stat.S_IROTH,
        )
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(item.content)
        created.append(item.path)
    return created, skipped
